package Practice;

public class IncrementDecrement {
    public static void main(String[] args) {

        int x = 5;

        System.out.println(x);
        System.out.println("After Increment:" + x++);
        System.out.println("After Decrement:" + x--);

        int a = 10;

        System.out.println(a++);
        System.out.println(++a);
        System.out.println(a--);
        System.out.println(--a);
 

    }
}


